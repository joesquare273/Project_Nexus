// Art for the menus (home tiles, the sign-in page): a card from anywhere in
// Magic, chosen for what its art shows, not tied to the sets the game plays.
// Saves each card's art crop and artist to data/ui-art.json; the client loads
// the image from Scryfall's image servers. The game never calls the API.
//
//   node packages/cards/scripts/ui-art.ts
//
// To change a picture, change its card below and run the script again.

import { writeFileSync } from 'node:fs';

/** Where each picture is used, and the card (exact printing) whose art it shows. */
const UI_ART: Record<string, { name: string; set: string; why: string }> = {
  playComputer: { name: 'Single Combat', set: 'war', why: 'Home: play the computer, two duelists' },
  playFriends: { name: 'Friendly Rivalry', set: 'ltr', why: 'Home: play friends' },
  draft: { name: 'Cogwork Librarian', set: 'cns', why: 'Home: booster draft (the classic draft card)' },
  packs: { name: 'Booster Tutor', set: 'unh', why: 'Home: open packs (the art is a booster pack)' },
  collection: { name: 'Hoarding Dragon', set: 'm11', why: 'Home: your collection (a dragon on its hoard)' },
  decks: { name: 'The Deck of Many Things', set: 'afr', why: 'Home: your decks' },
  craft: { name: 'Kenku Artificer', set: 'clb', why: 'Home and Craft: crafting cards' },
  store: { name: 'Black Market Connections', set: 'clb', why: 'Home: the Store' },
  learn: { name: 'Teach by Example', set: 'stx', why: 'Sign-in: learn as you play' },
};

const HEADERS = { 'User-Agent': 'ProjectNexus/0.1 (personal project; ui art script)', Accept: 'application/json', 'Content-Type': 'application/json' };

interface Card {
  name: string;
  set: string;
  collector_number: string;
  artist?: string;
  image_uris?: { art_crop: string; normal: string };
  card_faces?: { image_uris?: { art_crop: string; normal: string } }[];
  scryfall_uri: string;
}

const res = await fetch('https://api.scryfall.com/cards/collection', {
  method: 'POST',
  headers: HEADERS,
  body: JSON.stringify({ identifiers: Object.values(UI_ART).map((a) => ({ name: a.name, set: a.set })) }),
});
if (!res.ok) throw new Error(`${res.status} ${res.statusText} from Scryfall`);
const body = (await res.json()) as { data: Card[]; not_found: unknown[] };
if (body.not_found.length) throw new Error(`Not found on Scryfall: ${JSON.stringify(body.not_found)}`);

const out: Record<string, unknown> = {
  $comment: 'Menu art (home tiles, sign-in page) from cards anywhere in Magic. Generated by scripts/ui-art.ts; images load from Scryfall.',
};
for (const [key, want] of Object.entries(UI_ART)) {
  const card = body.data.find((c) => c.name === want.name && c.set === want.set);
  if (!card) throw new Error(`No ${want.name} (${want.set}) in Scryfall's answer.`);
  const image = card.image_uris ?? card.card_faces?.[0]?.image_uris;
  if (!image) throw new Error(`${card.name} has no image.`);
  out[key] = { name: card.name, set: card.set, number: card.collector_number, artist: card.artist ?? '', artCrop: image.art_crop, scryfallUri: card.scryfall_uri, why: want.why };
  console.log(`${key}: ${card.name} (${card.set} #${card.collector_number}) by ${card.artist}`);
}
writeFileSync(new URL('../data/ui-art.json', import.meta.url), `${JSON.stringify(out, null, 2)}\n`);
