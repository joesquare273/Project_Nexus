// The card database. Cards are data, not code: adding a card that uses
// existing effects means editing JSON only.

import { canBeCommander } from '@nexus/engine';
import type { CardDefId, CardDefinition } from '@nexus/engine';
import kitsData from '../data/fin-starter-kits.json' with { type: 'json' };
import fin from '../data/fin.json' with { type: 'json' };
import fic from '../data/fic.json' with { type: 'json' };
import finSet from '../data/fin-set.json' with { type: 'json' };
import ficPrecons from '../data/fic-precons.json' with { type: 'json' };
import lands from '../data/lands.json' with { type: 'json' };
import preconPrintings from '../data/precon-printings.json' with { type: 'json' };
import scryfall from '../data/scryfall.json' with { type: 'json' };
import tokens from '../data/tokens.json' with { type: 'json' };
import { validateCardList } from './validate.ts';

export { validateCardDefinition, validateCardList } from './validate.ts';

/**
 * Basic lands and Towns are in lands.json; every other Starter Kit card is
 * in fin.json; the Commander precons' other cards are in fic.json
 * (generated by scripts/import-precons.ts); the rest of the Final Fantasy main
 * set and Through the Ages are in fin-set.json (scripts/import-sets.ts, for
 * sealed play); tokens are in tokens.json.
 */
const all = [...lands, ...fin, ...fic, ...finSet, ...tokens];
const errors = validateCardList(all);
if (errors.length > 0) throw new Error(`Invalid card data:\n${errors.join('\n')}`);

export const CARDS = all as CardDefinition[];
export const CARD_DEFS: Record<CardDefId, CardDefinition> = Object.fromEntries(CARDS.map((c) => [c.id, c]));

export interface KitCard {
  name: string;
  count: number;
  set: string;
  number: string;
  implemented: boolean;
  /** Engine features this card needs before it can be implemented. */
  needs: string[];
}

export interface StarterKit {
  name: string;
  total: number;
  cards: KitCard[];
}

export const FIN_STARTER_KITS = kitsData.kits as StarterKit[];

/** Scryfall details for a real card: image links (loaded from Scryfall at runtime) and Oracle text. */
export interface ScryfallInfo {
  name: string;
  typeLine: string;
  oracleText: string;
  set: string;
  number: string;
  artist?: string;
  image: { small: string; normal: string; large: string; artCrop: string };
  scryfallUri: string;
  scryfallId?: string;
  /** Tokens this card makes, per Scryfall's related parts. */
  relatedTokens?: { name: string; scryfallId: string }[];
}

/** By card id. Refresh with `npm run scryfall`. Placeholder cards have no entry. */
export const SCRYFALL: Record<CardDefId, ScryfallInfo> = scryfall;
/** Artwork by physical printing; variants share the same engine card definition. */
export const SCRYFALL_PRINTINGS: Record<string,ScryfallInfo> = Object.fromEntries(
  [...Object.values(SCRYFALL), ...Object.values(preconPrintings)].map(info=>[info.set+'/'+info.number,info]),
);
export interface PrintedPrecon { commander: CardDefId; deck: CardDefId[]; commanderPrinting: { set:string; number:string }; deckPrintings: { set:string; number:string }[] }

export interface PreconDeck {
  name: string;
  commander: KitCard;
  colorIdentity: string[];
  /** The other 99 cards. */
  cards: KitCard[];
}

/** The four Final Fantasy Commander precons (100 cards each, including the commander). */
export const FIN_PRECONS = ficPrecons.decks as PreconDeck[];

/** Card ids by exact card name, for turning decklists into decks. */
export const CARD_IDS_BY_NAME: Record<string, CardDefId> = Object.fromEntries(CARDS.map((c) => [c.name, c.id]));

/**
 * One of the two Final Fantasy Starter Kit decks, exactly as printed: 60
 * cards, including cards that aren't built yet (see `notBuilt`). Used by the
 * browser game, the terminal game, the simulator and the fuzz tests.
 */
export function starterKitDeck(colors: 'RW' | 'UB'): CardDefId[] {
  const kit = FIN_STARTER_KITS.find((k) => k.name.endsWith(colors === 'RW' ? 'Red-White' : 'Blue-Black'))!;
  return kit.cards.flatMap((c) => {
    const id = CARD_IDS_BY_NAME[c.name];
    if (!id) throw new Error(`No card definition for "${c.name}".`);
    return Array<CardDefId>(c.count).fill(id);
  });
}

/** A card in a precon that could lead it. */
export interface CommanderChoice {
  name: string;
  defId: CardDefId;
  colorIdentity: string[];
  /** Its abilities are built (unbuilt cards can't be cast or played). */
  built: boolean;
  /** The precon's printed commander. */
  printed: boolean;
}

/**
 * The cards in a precon that could be its commander: legendary creatures and
 * legendary Vehicles whose colors cover every card in the deck (rules 903.3,
 * 903.5c). The printed commander comes first.
 */
export function preconCommanders(name: string): CommanderChoice[] {
  const precon = FIN_PRECONS.find((p) => p.name === name || p.name.startsWith(name));
  if (!precon) throw new Error(`No precon named "${name}".`);
  const all = [precon.commander, ...precon.cards];
  const deckColors = new Set(all.flatMap((c) => CARD_DEFS[CARD_IDS_BY_NAME[c.name]!]?.colorIdentity ?? []));
  const choices: CommanderChoice[] = [];
  for (const c of all) {
    const def = CARD_DEFS[CARD_IDS_BY_NAME[c.name]!];
    if (!def || !canBeCommander(def)) continue;
    const colors = def.colorIdentity ?? [];
    if (![...deckColors].every((k) => colors.includes(k as never))) continue;
    choices.push({ name: def.name, defId: def.id, colorIdentity: colors, built: !def.notBuilt, printed: c === precon.commander });
  }
  return choices.sort((a, b) => Number(b.printed) - Number(a.printed));
}

/**
 * A precon as a commander plus a 99-card library, for createGame. With
 * `commanderName` (one of `preconCommanders`), that card leads it and the
 * printed commander joins the 99.
 */
export function preconDeckWithCommander(name: string, commanderName?: string): PrintedPrecon {
  const base = preconDeck(name);
  if (!commanderName) return base;
  const choice = preconCommanders(name).find((c) => c.name === commanderName);
  if (!choice) throw new Error(`${commanderName} can't lead ${name}: it must be a legendary creature or Vehicle in all of the deck's colors.`);
  if (choice.printed) return base;
  const deck = [...base.deck];
  const at=deck.indexOf(choice.defId), deckPrintings=[...base.deckPrintings];
  const commanderPrinting=deckPrintings.splice(at,1)[0]!;
  deck.splice(at,1); deck.push(base.commander); deckPrintings.push(base.commanderPrinting);
  return { commander:choice.defId,deck,commanderPrinting,deckPrintings };
}

/** A precon as a commander plus a 99-card library, for createGame. */
export function preconDeck(name: string): PrintedPrecon {
  const precon = FIN_PRECONS.find((p) => p.name === name || p.name.startsWith(name));
  if (!precon) throw new Error(`No precon named "${name}".`);
  const id = (cardName: string) => {
    const found = CARD_IDS_BY_NAME[cardName];
    if (!found) throw new Error(`No card definition for "${cardName}".`);
    return found;
  };
  return {
    commander: id(precon.commander.name),
    commanderPrinting: {set:precon.commander.set,number:precon.commander.number},
    deckPrintings: precon.cards.flatMap(c=>Array.from({length:c.count},()=>({set:c.set,number:c.number}))),
    deck: precon.cards.flatMap((c) => Array<CardDefId>(c.count).fill(id(c.name))),
  };
}
